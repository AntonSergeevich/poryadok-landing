"""Хранилище статики с отпечатками, которое не роняет сайт.

Отпечатки в именах файлов (`site.19ced5cb.css`) нужны из-за кэша: nginx
отдаёт статику на 30 дней, и без смены имени посетитель после обновления
продолжает видеть старые стили.

Плата за это — зависимость: чтобы собрать адрес файла, Django читает
справочник отпечатков, который создаёт `collectstatic`. Если справочника
нет или в нём нет нужной записи, обычное хранилище поднимает исключение.
Звучит строго и правильно — пока не посмотреть, где это происходит:

* при отрисовке любой страницы, где есть `{% static %}` — то есть на всех;
* при загрузке `landing/urls.py`, если адрес вычисляется там же.

Итог одинаковый: забыли `collectstatic` при выкладке — и сайт отдаёт 500
на каждой странице из-за одной иконки. Причём `collectstatic` в этом
состоянии тоже не запускается: перед работой он прогоняет проверки и
импортирует те же маршруты. Круг замыкается, и чинить приходится
с флагом `--skip-checks`.

Размен очевиден: отпечаток на одном файле не стоит лежащего сайта.
Поэтому не сумев вычислить имя, отдаём обычный путь без отпечатка —
файл откроется, просто без защиты от кэша, — и пишем в журнал, чтобы
причина не осталась незамеченной.

Строгость при этом не теряется там, где она нужна: сам `collectstatic`
по-прежнему честно ругается на битые ссылки внутри CSS.
"""
import logging

from django.conf import settings
from django.contrib.staticfiles.storage import ManifestStaticFilesStorage

logger = logging.getLogger(__name__)


class ForgivingManifestStaticFilesStorage(ManifestStaticFilesStorage):
    # Не найдя запись в справочнике, не поднимаем исключение сразу,
    # а даём url() возможность вычислить имя по самому файлу.
    manifest_strict = False

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        # О каждом файле жалуемся один раз, а не на каждый запрос:
        # иначе журнал забьётся тысячами одинаковых строк за минуту.
        self._complained = set()

    def url(self, name, force=False):
        try:
            return super().url(name, force=force)
        except ValueError:
            if name not in self._complained:
                self._complained.add(name)
                logger.warning(
                    'Статика: не удалось вычислить отпечаток для «%s». '
                    'Скорее всего не выполнен collectstatic. Отдаю путь без '
                    'отпечатка — файл откроется, но может прийти из кэша.', name)
            return f'{settings.STATIC_URL}{name}'
