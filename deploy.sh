#!/usr/bin/env bash
#
# Выкладка на боевой сервер одной командой.
#
#   cd /var/www/s-poryadok
#   bash deploy.sh                        выложить текущую ветку
#   bash deploy.sh main                   выложить main
#   bash deploy.sh --check                ничего не менять, только показать
#
# Почему это скрипт, а не список команд в инструкции.
#
# Список команд в терминале выполняется независимо: если вторая упала,
# третья всё равно выполнится. Ровно это однажды и произошло — git pull
# отказался из-за правки прямо на сервере, а migrate, collectstatic
# и restart прошли дальше как ни в чём не бывало. В журнале всё зелёное,
# gunicorn перезапущен, а сайт остался на старом коде: обновление
# «прошло», ничего не обновив.
#
# Здесь такое невозможно: set -e останавливает всё на первом же отказе,
# а в конце скрипт проверяет, что выложено именно то, что собирались,
# и что сайт после этого отвечает.
#
# Что делает по шагам:
#   1. проверяет, что запущен там, где надо, и что рабочая копия чистая
#   2. копирует базу — до миграций, а не после
#   3. забирает ветку и приводит рабочую копию ровно к ней
#   4. ставит зависимости, если requirements.txt изменился
#   5. миграции, статика, папка для вложений
#   6. перезапускает gunicorn и перечитывает nginx
#   7. проверяет, что сайт отвечает, и что версия и правда новая
#
# Ничего не удаляет безвозвратно: правки в файлах проекта уходят
# в git stash, файлы, сделанные на сервере, — переименовываются рядом,
# старые копии базы хранятся две недели.

set -Eeuo pipefail

# ── Запуск из копии ──────────────────────────────────────────────────
#
# Скрипт обновляет сам себя вместе с остальным кодом: он лежит в том же
# репозитории. А bash читает файл по мере выполнения, а не целиком —
# и если git подменит его на середине, дальше выполнится мусор
# с середины новой версии. Поймать такое потом почти невозможно.
#
# Поэтому первым делом снимаем копию и работаем из неё. Файл в проекте
# после этого может меняться сколько угодно.

if [ -z "${DEPLOY_FROM_COPY:-}" ]; then
  SELF="$(mktemp)"
  cat "$0" > "$SELF"
  export DEPLOY_FROM_COPY=1
  bash "$SELF" "$@"
  CODE=$?
  rm -f "$SELF"
  exit $CODE
fi

# ── Настройки ────────────────────────────────────────────────────────

ROOT="${ROOT:-/var/www/s-poryadok}"
VENV="${VENV:-$ROOT/venv}"
DOMAIN="${DOMAIN:-s-poryadok.ru}"
SOCK="${SOCK:-/run/gunicorn.sock}"
KEEP_BACKUPS="${KEEP_BACKUPS:-14}"
BACKUPS="$ROOT/backups"

# ── Вид ──────────────────────────────────────────────────────────────

if [ -t 1 ]; then
  B=$'\e[1m'; R=$'\e[31m'; G=$'\e[32m'; Y=$'\e[33m'; N=$'\e[0m'
else
  B=''; R=''; G=''; Y=''; N=''
fi

step()  { echo -e "\n${B}── $* ${N}"; }
ok()    { echo -e "  ${G}✓${N} $*"; }
warn()  { echo -e "  ${Y}!${N} $*"; }
die()   { echo -e "\n${R}✗ $*${N}\n" >&2; exit 1; }

# Любой необработанный сбой должен объяснить себя, а не молча оборвать
# вывод на середине.
trap 'die "Сорвалось на строке $LINENO. Выше видно, на чём именно.
Сайт при этом остался на прежней версии — до перезапуска дело не дошло."' ERR

CHECK_ONLY=0
BRANCH=""
for arg in "$@"; do
  case "$arg" in
    --check|-n) CHECK_ONLY=1 ;;
    -*) die "Не знаю ключ «$arg». Есть только --check." ;;
    *)  BRANCH="$arg" ;;
  esac
done

# ── 1. Где мы и всё ли на месте ──────────────────────────────────────

step "Проверки перед началом"

[ -d "$ROOT/.git" ] || die "В $ROOT нет репозитория.
Если проект лежит в другом месте: ROOT=/путь bash deploy.sh"
cd "$ROOT"

[ -x "$VENV/bin/python" ] || die "Нет окружения в $VENV.
Создать: python3 -m venv venv && venv/bin/pip install -r requirements.txt"
PY="$VENV/bin/python"
PIP="$VENV/bin/pip"
ok "проект: $ROOT"

command -v git >/dev/null || die "Нет git."

# Ветка: явно указанная, иначе та, на которой стоим сейчас.
if [ -z "$BRANCH" ]; then
  BRANCH="$(git rev-parse --abbrev-ref HEAD)"
  [ "$BRANCH" != "HEAD" ] || die "Репозиторий не на ветке.
Укажите ветку явно: bash deploy.sh <ветка>"
fi
ok "ветка: $BRANCH"

WAS="$(git rev-parse --short HEAD)"
ok "сейчас выложено: $WAS"

# ── 2. Правки прямо на сервере ───────────────────────────────────────
#
# Их не должно быть: сервер — это копия репозитория, а не место для
# работы. Но они появляются — что-то поправили «на минутку» и забыли.
# Стереть их молча нельзя: возможно, это единственная копия починки.
# Поэтому убираем в stash и говорим, как достать обратно.

step "Правки на сервере"

if ! git diff --quiet || ! git diff --cached --quiet; then
  warn "рабочая копия изменена прямо на сервере:"
  git --no-pager diff --stat HEAD | sed 's/^/      /'

  if [ "$CHECK_ONLY" = 1 ]; then
    warn "при настоящей выкладке они уйдут в git stash"
  else
    STASH="перед выкладкой $(date '+%F %H:%M')"
    # Только изменённые отслеживаемые файлы. Неотслеживаемые не трогаем:
    # ни checkout, ни reset --hard их не удаляют, прятать нечего, —
    # а --include-untracked однажды утащил в stash сам этот скрипт,
    # пока он ещё не был в репозитории.
    git stash push -m "$STASH" >/dev/null
    ok "убраны в stash: «$STASH»"
    echo "      вернуть:  git stash list  →  git stash pop"
  fi
else
  ok "чисто"
fi

# ── 3. Копия базы ────────────────────────────────────────────────────
#
# До миграций, а не после: миграция меняет структуру, и копия, снятая
# после неё, откатить уже не поможет.

step "Копия базы"

mkdir -p "$BACKUPS"

# Какая база работает — решает .env, а не то, какие файлы лежат рядом.
# После переезда на PostgreSQL файл db.sqlite3 остаётся на месте
# и выглядит как настоящая база. Копировать его вместо работающей —
# это делать бесполезные копии и не делать нужных: миграции пойдут
# по PostgreSQL, а откатывать будет нечего.
PG_URL="$(grep -E '^DATABASE_URL=' "$ROOT/.env" 2>/dev/null | head -1 | cut -d= -f2- || true)"

if [ -n "$PG_URL" ]; then
  COPY="$BACKUPS/db-$(date +%F-%H%M).sql.gz"
  if [ "$CHECK_ONLY" = 1 ]; then
    warn "снял бы копию PostgreSQL в $COPY"
  elif ! command -v pg_dump >/dev/null 2>&1; then
    # Без копии миграции не запускаем вовсе. Выложить код можно ещё раз,
    # потерянные данные — нельзя.
    die "База — PostgreSQL, а pg_dump не установлен: копию снять нечем.
Поставить:  sudo apt install -y postgresql-client"
  else
    # Пароль в адресе, поэтому сам адрес нигде не печатаем.
    if pg_dump "$PG_URL" 2>/dev/null | gzip > "$COPY"; then
      ok "база: $COPY ($(du -h "$COPY" | cut -f1))"
      ls -1t "$BACKUPS"/db-*.sql.gz 2>/dev/null \
        | tail -n +$((KEEP_BACKUPS + 1)) | xargs -r rm --
    else
      rm -f "$COPY"
      die "pg_dump не сработал — копии нет, дальше не иду.
Проверить вручную:  pg_dump \"\$DATABASE_URL\" > /dev/null"
    fi
  fi
elif [ -f "$ROOT/db.sqlite3" ]; then
  COPY="$BACKUPS/db-$(date +%F-%H%M).sqlite3"
  if [ "$CHECK_ONLY" = 1 ]; then
    warn "скопировал бы базу в $COPY"
  else
    # sqlite3 .backup умеет копировать базу, в которую в этот момент
    # пишут. Обычный cp на живой базе может дать битый файл — именно
    # тогда, когда он нужнее всего.
    if command -v sqlite3 >/dev/null; then
      sqlite3 "$ROOT/db.sqlite3" ".backup '$COPY'"
    else
      cp "$ROOT/db.sqlite3" "$COPY"
      warn "нет sqlite3, копировал обычным cp — поставьте: apt install sqlite3"
    fi
    ok "база: $COPY ($(du -h "$COPY" | cut -f1))"

    # Старые копии убираем, оставляя последние. Диск на VPS кончается
    # тихо, и кончается он обычно бэкапами.
    ls -1t "$BACKUPS"/db-*.sqlite3 2>/dev/null \
      | tail -n +$((KEEP_BACKUPS + 1)) | xargs -r rm --
  fi
else
  warn "файла db.sqlite3 нет — копировать нечего"
fi

# ── 4. Забрать код ───────────────────────────────────────────────────

step "Забираю код"

git fetch --prune origin "$BRANCH" \
  || die "Не удалось забрать с GitHub. Проверьте сеть и доступ."

REMOTE="$(git rev-parse --short "origin/$BRANCH")"
ok "в репозитории: $REMOTE"

if [ "$WAS" = "$REMOTE" ]; then
  ok "уже выложено — нового нет"
else
  echo "      что приедет:"
  git --no-pager log --oneline "HEAD..origin/$BRANCH" | head -20 | sed 's/^/      /'
fi

if [ "$CHECK_ONLY" = 1 ]; then
  echo -e "\n${B}Проверка окончена, ничего не менял.${N}\n"
  exit 0
fi

# Файлы, сделанные на сервере руками, которые теперь приехали
# в репозитории.
#
# Так бывает чаще, чем кажется: что-то создали прямо на сервере, потом
# ровно такой же файл добавили в проект. Для git это столкновение, и
# ведёт он себя в двух случаях по-разному: checkout отказывается
# и останавливает выкладку, reset --hard молча затирает. Не годится
# ни то, ни другое — в первом случае обновление встаёт, во втором
# бесследно пропадает чужая работа.
#
# Отодвигаем в сторону и говорим куда.
MOVED=0
while IFS= read -r file; do
  [ -n "$file" ] || continue
  [ -e "$file" ] || continue
  git ls-files --error-unmatch "$file" >/dev/null 2>&1 && continue

  KEEP="$file.до-выкладки-$(date +%H%M)"
  mkdir -p "$(dirname "$KEEP")"
  mv "$file" "$KEEP"
  warn "«$file» был сделан на сервере, а теперь есть и в проекте"
  echo "      ваш вариант сохранён: $KEEP"
  MOVED=$((MOVED + 1))
done < <(git ls-tree -r --name-only "origin/$BRANCH")
[ "$MOVED" = 0 ] || ok "отодвинуто файлов: $MOVED"

# reset --hard, а не merge: рабочая копия должна стать ровно тем, что
# лежит в репозитории. Merge здесь может встать на конфликте и оставить
# сервер в половинчатом состоянии — худшем из возможных.
# Правки в отслеживаемых файлах уже в stash, столкновения отодвинуты:
# терять нечего.
git checkout -B "$BRANCH" "origin/$BRANCH" >/dev/null 2>&1
git reset --hard "origin/$BRANCH" >/dev/null
NOW="$(git rev-parse --short HEAD)"

[ "$NOW" = "$REMOTE" ] || die "После обновления HEAD = $NOW, а ожидался $REMOTE.
Дальше не иду: непонятно, что именно выложено."
ok "выложено: $NOW"

# ── 5. Зависимости ───────────────────────────────────────────────────
#
# Ставим всегда. Раньше — только если requirements.txt изменился между
# «было» и «стало», и это ровно один раз обошлось в лежащий сайт.
#
# Дело в том, что «было» и «стало» — это два коммита, а не два состояния
# машины. Если код уже забрали руками (git pull), к моменту запуска
# скрипта они совпадают, разницы нет — и pip не запускается вовсе,
# хотя в проекте появилась новая библиотека. Скрипт при этом бодро
# сообщает «не менялись»: он сравнил не то, что важно.
#
# Важно другое: стоит ли на машине то, что нужно коду. Ответ на это
# знает pip, и спрашивать надо его. Когда всё на месте, он отвечает
# за секунду и ничего не делает.

step "Зависимости"

$PIP install -q -r requirements.txt || die "pip не смог поставить зависимости.
Дальше не иду: код обновлять без библиотек, которые ему нужны, бессмысленно."
ok "всё на месте"

# ── 5а. Проверка, что код вообще живой ───────────────────────────────
#
# Между «файлы обновились» и «сайт работает» есть шаг, который до сих
# пор никто не делал: спросить у Django, всё ли у него в порядке.
#
# Проверка нужна именно здесь, до миграций. Django отказывается работать
# при некоторых ошибках — например, если модель просит библиотеку,
# которой нет, — и отказывается он одинаково для всех команд. Значит,
# следующая же команда молча ничего не сделает, а скрипт этого
# не заметит и пойдёт дальше.

step "Проверка кода"

if ! CHECK="$($PY manage.py check 2>&1)"; then
  echo "$CHECK" | sed 's/^/  /'
  die "Django не принимает этот код.
Выше сказано, что именно ему не нравится. Чаще всего это отсутствующая
библиотека — тогда помогает:  $PIP install -r requirements.txt"
fi
ok "Django принимает код"

# ── 6. База, статика, вложения ───────────────────────────────────────

step "Миграции"

# Список миграций спрашиваем так, чтобы отказ было видно. Раньше здесь
# стояло 2>/dev/null, и когда команда падала — а падала она целиком,
# по причине из предыдущего шага, — на экране появлялось «нечего
# применять». Миграции не применялись, сайт после выкладки открывал
# страницу, за которой нет таблиц, и искать причину приходилось
# в последнюю очередь: скрипт же сказал, что всё хорошо.
#
# Пустой ответ и ответ «ноль» — разные вещи, и путать их нельзя.
if ! PLAN="$($PY manage.py showmigrations --plan 2>&1)"; then
  echo "$PLAN" | tail -5 | sed 's/^/  /'
  die "Не смог посмотреть список миграций.
Это не «миграций нет» — это «не смог посмотреть». Пока непонятно,
что с базой, дальше идти нельзя."
fi

PENDING="$(printf '%s\n' "$PLAN" | grep -c '^\[ \]' || true)"
if [ "${PENDING:-0}" -gt 0 ]; then
  $PY manage.py migrate --noinput
  ok "применено миграций: $PENDING"
else
  ok "нечего применять"
fi

step "Статика"
# Отпечатки в именах файлов пересчитываются здесь. Без этого браузеры
# посетителей продолжат показывать старый CSS: nginx отдаёт статику
# с кэшем на месяц.
$PY manage.py collectstatic --noinput 2>&1 | tail -1 | sed 's/^/  /'

step "Папка для вложений"
mkdir -p "$ROOT/media"
# Файлы пишет gunicorn, а раздаёт nginx — оба под www-data.
if id -u www-data >/dev/null 2>&1; then
  chown -R www-data:www-data "$ROOT/media"
  ok "media/ готова, владелец www-data"
else
  warn "пользователя www-data нет — проверьте владельца media/ вручную"
fi

# Раздача вложений живёт в конфиге nginx. Без неё файлы из переписки
# просто не откроются, и понять почему будет неоткуда.
#
# Состояний тут три, и путать их нельзя. Первая версия проверки читалась
# как «if nginx -T не содержит /media/» — и молча объединяла «раздачи
# нет» с «nginx не запустился, и смотреть было не в чем». На сервере,
# где раздача была на месте, скрипт уверенно сообщил, что её нет.
#
# Это ровно тот сорт вранья, ради которого скрипт и затевался: выдать
# непроверенное за проверенное. Поэтому вывод nginx забираем отдельно
# и смотрим, получилось ли вообще.
NGINX_CONF=""
if command -v nginx >/dev/null 2>&1; then
  NGINX_CONF="$(nginx -T 2>/dev/null || true)"
fi

if [ -z "$NGINX_CONF" ]; then
  warn "конфиг nginx прочитать не вышло — раздачу /media/ не проверял"
  echo "      посмотреть самому:  sudo bash scripts/nginx-setup.sh"
elif ! printf '%s' "$NGINX_CONF" | grep -q 'location /media/'; then
  warn "в nginx нет раздачи /media/ — вложения в переписке не откроются"
  echo "      поставить:  sudo bash scripts/nginx-setup.sh --apply"
fi

# ── 7. Перезапуск ────────────────────────────────────────────────────

step "Перезапуск"

systemctl restart gunicorn
ok "gunicorn перезапущен"

# Конфиг nginx мы не меняли, но перечитать дёшево, а забыть — дорого.
if nginx -t >/dev/null 2>&1; then
  systemctl reload nginx
  ok "nginx перечитал конфиг"
else
  warn "конфиг nginx с ошибкой — не перечитывал, старый продолжает работать"
  nginx -t 2>&1 | sed 's/^/      /'
fi

# ── 8. Проверка, что всё это сработало ───────────────────────────────
#
# Самая важная часть. Без неё скрипт сообщает об успехе ровно так же,
# как сообщал бы о выкладке на сломанный сайт.

step "Проверка"

# Gunicorn поднимается не мгновенно. Даём ему несколько попыток, а не
# одну: единственная проверка сразу после restart регулярно ловит
# ещё не открытый сокет и пугает зря.
CODE=000
for attempt in 1 2 3 4 5 6; do
  sleep 2
  # curl с -w печатает 000 сам, когда соединиться не удалось. Добавочный
  # «|| echo 000» дописал бы вторую тройку, и в сообщении об ошибке
  # оказалось бы «кодом 000000» — число, которого не бывает, и человек
  # начал бы искать поломку не там.
  # Заголовок Host обязателен. Через сокет запрос идёт мимо nginx,
  # и curl подставляет «localhost» — а его нет в ALLOWED_HOSTS, потому
  # что боевой сайт живёт под своим именем. Django на такой запрос
  # отвечает 400, и проверка объявляла рабочий сайт сломанным.
  CODE="$(curl -sS -o /dev/null --max-time 10 -w '%{http_code}' \
          -H "Host: $DOMAIN" --unix-socket "$SOCK" http://localhost/ 2>/dev/null || true)"
  CODE="${CODE:-000}"
  [ "$CODE" = "200" ] && break
done

if [ "$CODE" != "200" ]; then
  if [ "$CODE" = "400" ]; then
    warn "код 400 обычно означает, что имени «$DOMAIN» нет в ALLOWED_HOSTS"
    warn "проверьте core/settings.py — сам Django при этом жив"
  fi
  # Настоящая причина, а не хвост журнала.
  #
  # Раньше здесь печатались двадцать последних строк app.log — и в них
  # оказывались записи недельной давности про Telegram, не имеющие
  # к поломке никакого отношения. Ошибка запроса туда не попадает,
  # и человек читал случайный текст вместо ответа.
  #
  # Теперь тот же запрос делается изнутри Django, с включённым
  # показом ошибок. Это даёт настоящий разбор: имя исключения, файл
  # и строку. Наружу это не выходит — команда выполняется на сервере
  # и печатает в терминал тому, кто и так имеет к нему доступ.
  echo
  echo "  Что говорит сам Django:"
  SITE_DOMAIN="$DOMAIN" $PY - <<'PYCODE' 2>&1 | tail -25 | sed 's/^/  /'
import os, traceback
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'core.settings')
import django
django.setup()
