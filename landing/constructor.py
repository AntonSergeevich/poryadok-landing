# Скидка за объём. Не «маркетинг»: пятый блок собирается вчетверо быстрее
# первого — модели, доступы и сборка уже сделаны, остаётся сама работа.
# Не поделиться этим значит брать деньги за то, чего не делаешь.
BUNDLE_STEPS = ((6, 0.12), (4, 0.07))


def by_id(block_id):
    for block in BLOCKS:
        if block['id'] == block_id:
            return block
    return None


def core_ids():
    return [block['id'] for block in BLOCKS if block['core']]


def scale_by_id(scale_id):
    for scale in SCALES:
        if scale['id'] == scale_id:
            return scale
    return SCALES[0]


def clean(chosen):
    """Оставить только известные блоки и добавить ядро.

    Ядро дописывается молча: выключить его нельзя, а спорить об этом
    с тем, кто правит адрес руками, незачем.
    """
    known = {block['id'] for block in BLOCKS}
    picked = [b for b in (chosen or []) if b in known]
    for block_id in core_ids():
        if block_id not in picked:
            picked.append(block_id)
    # Порядок берём из BLOCKS, а не из того, в каком человек нажимал:
    # схема должна выглядеть одинаково при одинаковом наборе.
    return [block['id'] for block in BLOCKS if block['id'] in picked]


def estimate(chosen, scale_id='solo'):
    """Во что обходится собранный состав.

    Считает один и тот же код и на странице, и при отправке заявки.
    Двух реализаций быть не должно: расхождение между «посчитал сайт»
    и «назвал я» — ровно тот разговор, от которого система избавляет.
    """
    picked = clean(chosen)
    blocks = [by_id(block_id) for block_id in picked]
    scale = scale_by_id(scale_id)

    raw = sum(block['price'] for block in blocks)
    extra = len([b for b in blocks if not b['core']])

    discount = 0.0
    for count, value in BUNDLE_STEPS:
        if extra >= count:
            discount = value
            break

    scaled = raw * scale['k']
    total = scaled * (1 - discount)

    return {
        'ids': picked,
        'blocks': blocks,
        'scale': scale,
        'raw': int(round(raw)),
        'extra': extra,
        'discount': int(round(discount * 100)),
        'saved': int(round(scaled - total)),
        # Округляем до тысячи вверх: «163 750 ₽» выглядит как расчёт,
        # которого никто не делал, и вызывает вопрос вместо доверия.
        'total': int(-(-total // 1000) * 1000),
    }


def suggest(diagnosis):
    """Что отметить человеку, пришедшему с разбора.

    Берём боли, которые тест нашёл у него, и включаем блоки, которые их
    закрывают. Это не подбор «побольше»: блок без совпадения по боли
    остаётся выключенным, и человек сам решает, нужен ли он.
    """
    if not diagnosis:
        return core_ids()

    hurts = {item['key'] for item in diagnosis.get('top') or []}
    picked = [block['id'] for block in BLOCKS
              if block['core'] or (set(block['areas']) & hurts)]
    return picked or core_ids()


def as_text(picked, scale_id, total):
    """Строка для заявки и для уведомления в Telegram.

    Заявка «расскажите про цены» и заявка «нужны запись, оплаты и
    напоминания, примерно 190 000» — это два разных разговора, и второй
    начинается с середины.
    """
    names = [block['title'] for block in (by_id(i) for i in picked) if block]
    scale = scale_by_id(scale_id)
    return (f'Собрал в конструкторе: {", ".join(names)}. '
            f'{scale["title"]}. Ориентир: от {total:,} ₽'.replace(',', ' '))
