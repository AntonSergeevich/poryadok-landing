"""Договор возмездного оказания услуг: текст, реквизиты и число прописью.

Почему текст лежит здесь, а не в шаблоне
----------------------------------------

Договор — не страница. Его печатают, подписывают и хранят, и через год
надо уметь ответить, что именно было подписано. Поэтому текст живёт
данными: он собирается в структуру, структура подставляется в шаблон,
а **подписанный договор хранится снимком** — правка этого файла не меняет
ни одного уже выставленного документа. Иначе получилось бы, что стороны
подписали один текст, а система показывает другой.

Что здесь важно знать
---------------------

Я не юрист. Этот текст собран по тому, как устроены такие договоры,
и закрывает те места, где обычно и возникают споры: что считается
результатом, когда он считается принятым, кому принадлежит код, что
делать с персональными данными клиентов заказчика и что происходит, если
одна из сторон передумала. Перед первым подписанием его должен прочитать
юрист — список вопросов, которые стоит ему задать, собран в LAWYER_NOTES
и показывается в кабинете рядом с договором.

Отдельно про самозанятость. Исполнитель применяет налог на
профессиональный доход, и у заказчика-юрлица от этого два риска:
переквалификация в трудовые отношения и утрата исполнителем права
на НПД посреди работы. Оба закрыты пунктами договора (1.5, 3.6), и оба —
не формальность: без них бухгалтерия заказчика имеет полное право
не подписывать.
"""
