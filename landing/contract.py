# ── Число прописью ───────────────────────────────────────────────────
#
# В договоре сумма пишется дважды: цифрами и словами. Это не традиция —
# дописать ноль к цифре можно, к слову «сто восемьдесят тысяч» нельзя.
# Поэтому прописью здесь считается кодом, а не вводится руками: сумма,
# набранная человеком, однажды разойдётся с цифрой в соседней строке.

_ONES = ('', 'один', 'два', 'три', 'четыре', 'пять',
         'шесть', 'семь', 'восемь', 'девять')
_ONES_F = ('', 'одна', 'две', 'три', 'четыре', 'пять',
           'шесть', 'семь', 'восемь', 'девять')
_TEENS = ('десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
          'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать',
          'девятнадцать')
_TENS = ('', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
         'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто')
_HUNDREDS = ('', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
             'шестьсот', 'семьсот', 'восемьсот', 'девятьсот')

# Разряды. Тысяча — женского рода («одна тысяча»), остальные мужского;
# ошибка здесь даёт «один тысяча», и договор с таким числом читают уже
# не как документ.
_SCALES = (
    (10 ** 9, ('миллиард', 'миллиарда', 'миллиардов'), False),
    (10 ** 6, ('миллион', 'миллиона', 'миллионов'), False),
    (10 ** 3, ('тысяча', 'тысячи', 'тысяч'), True),
)

RUBLES = ('рубль', 'рубля', 'рублей')
KOPECKS = ('копейка', 'копейки', 'копеек')


def plural(number, forms):
    """Форма слова при числе: 1 рубль, 2 рубля, 5 рублей.

    Одиннадцать–девятнадцать — исключение целиком: «одиннадцать рублей»,
    хотя оканчивается на единицу.
    """
    tail = abs(int(number)) % 100
    if 11 <= tail <= 19:
        return forms[2]
    tail %= 10
    if tail == 1:
        return forms[0]
    if 2 <= tail <= 4:
        return forms[1]
    return forms[2]


def _triple(value, female=False):
    words = []
    hundreds, rest = divmod(value, 100)
    if hundreds:
        words.append(_HUNDREDS[hundreds])
    tens, ones = divmod(rest, 10)
    if tens == 1:
        words.append(_TEENS[ones])
    else:
        if tens:
            words.append(_TENS[tens])
        if ones:
            words.append((_ONES_F if female else _ONES)[ones])
    return words


def words(value):
    """Целое число словами. 180000 -> «сто восемьдесят тысяч»."""
    value = int(value)
    if value == 0:
        return 'ноль'
    parts = []
    for scale, forms, female in _SCALES:
        group, value = divmod(value, scale)
        if group:
            parts.extend(_triple(group, female))
            parts.append(plural(group, forms))
    if value:
        parts.extend(_triple(value))
    return ' '.join(parts)


def money(amount):
    """«180 000 (сто восемьдесят тысяч) рублей 00 копеек».

    Копейки цифрами — так пишут в договорах и счетах: словами их читают
    хуже, а спорят из-за них реже, чем из-за рублей.
    """
    amount = Decimal(amount or 0).quantize(Decimal('0.01'))
    whole = int(amount)
    cents = int((amount - whole) * 100)
    # Неразрывный пробел: «189 000» не должно разорваться переносом
    # строки посередине суммы. В договоре это читается как две суммы.
    figure = f'{whole:,}'.replace(',', '\u00a0')
    return (f'{figure} ({words(whole)}) {plural(whole, RUBLES)} '
            f'{cents:02d} {plural(cents, KOPECKS)}')


