def missing_requisites():
    """Чего не хватает, чтобы договор можно было подписывать.

    Проверяется до выставления, а не после: договор без счёта заказчик
    получит, распечатает, подпишет — и только тогда спросит, куда платить.
    """
    have = executor()
    need = {
        'ex_name': 'имя исполнителя (SITE_OWNER)',
        'ex_inn': 'ИНН (SITE_INN)',
        'ex_address': 'адрес для писем (CONTRACT_ADDRESS)',
    }
    gaps = [title for key, title in need.items() if not have.get(key)]
    if not (have.get('ex_account') or have.get('ex_card')):
        gaps.append('счёт или карта для оплаты (CONTRACT_ACCOUNT / CONTRACT_CARD)')
    return gaps


class _Blanks(dict):
    """Подстановка, которая не падает на незаполненном.

    Договор с прочерком печатают и дописывают ручкой. Договор, который
    не собрался из-за одного пустого поля, не печатают вовсе.
    """

    def __missing__(self, key):
        return BLANK


MONTHS = ('января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля',
          'августа', 'сентября', 'октября', 'ноября', 'декабря')


def long_date(value):
    """«21» августа 2026 г. — так пишут дату в шапке договора."""
    if value is None:
        return BLANK
    return f'«{value.day:02d}» {MONTHS[value.month - 1]} {value.year} г.'


