def render(data):
    """Собрать текст договора: разделы с номерами и подставленными данными.

    Возвращает список словарей — то, что уйдёт и в шаблон, и в снимок.
    Снимок хранится у договора, поэтому здесь не должно остаться ничего,
    что понадобится вычислять при показе: подписанный документ обязан
    выглядеть одинаково и сегодня, и через три года.
    """
    filled = _Blanks(data)
    out = []
    for index, section in enumerate(SECTIONS, start=1):
        out.append({
            'number': index,
            'title': section['title'],
            'clauses': [
                {'number': f'{index}.{n}', 'text': text.format_map(filled)}
                for n, text in enumerate(section['clauses'], start=1)
            ],
        })
    return out


