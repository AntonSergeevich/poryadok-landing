/* Печать договора.

   Кнопка «Скачать PDF» открывает окно печати, где браузер сам предлагает
   «Сохранить как PDF». Своей сборки PDF здесь нет намеренно: она была бы
   второй вёрсткой того же документа и однажды разошлась бы с той, что
   человек видит на экране. Для договора это худший из возможных дефектов.

   Без скрипта кнопка бесполезна — поэтому она и появляется только
   вместе с ним. */
(function () {
  'use strict';

  document.addEventListener('click', function (e) {
    var button = e.target.closest ? e.target.closest('[data-print]') : null;
    if (!button) return;
    window.print();
  });
})();
