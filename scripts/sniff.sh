#!/usr/bin/env bash
# Что происходит между посетителем и сервером на уровне пакетов.
#
# Все замеры «изнутри» показывают здоровый сервер. Этот смотрит на провод:
# кто пришёл, что ответил сервер, на каком шаге разговор оборвался.
#
#   sudo bash scripts/sniff.sh                    # 120 секунд, все адреса
#   sudo bash scripts/sniff.sh 180                # 180 секунд
#   sudo bash scripts/sniff.sh 180 178.64.114.192 # только свой адрес
#
# Свой адрес можно узнать на телефоне, открыв 2ip.ru.
# Запускать В МОМЕНТ, КОГДА САЙТ НЕ ОТКРЫВАЕТСЯ, и всё это время
# обновлять сайт на телефоне.

set -u
SECS="${1:-120}"
ONLY="${2:-}"
DIR="$(cd "$(dirname "$0")/.." && pwd)"
RAW="$DIR/logs/sniff-raw.txt"
OUT="$DIR/logs/sniff.txt"
mkdir -p "$DIR/logs"

if ! command -v tcpdump >/dev/null 2>&1; then
  echo "Ставлю tcpdump..."
  apt-get install -y tcpdump >/dev/null 2>&1 || {
    echo "Не удалось. Выполните: sudo apt install tcpdump"; exit 1; }
fi

FILTER='tcp port 443 or tcp port 80'
[ -n "$ONLY" ] && FILTER="($FILTER) and host $ONLY"

echo "==========================================================="
echo " Слушаю $SECS секунд. Фильтр: $FILTER"
echo
echo " СЕЙЧАС обновляйте на телефоне:"
echo "   https://s-poryadok.ru/"
echo "==========================================================="
echo

# Без -q: нужны флаги, номера и опция mss. -s0 — целиком заголовки.
timeout "$SECS" tcpdump -i any -nn -l -s 0 "$FILTER" > "$RAW" 2>/dev/null
echo "Поймано строк: $(wc -l < "$RAW")"

# При -i any поля такие:
#   $1 время  $2 интерфейс  $3 In/Out  $4 IP  $5 источник  $6 >  $7 назначение:
srcip() { awk '{print $5}' "$1" | sed 's/\.[0-9]*$//'; }

{
echo "Отчёт снят: $(date '+%F %T %Z')"
echo "Слушали $SECS с, фильтр: $FILTER"
echo

TOTAL=$(wc -l < "$RAW")
echo "Всего пакетов: $TOTAL"

if [ "$TOTAL" -eq 0 ]; then
  cat <<'TXT'

ПАКЕТОВ НЕТ ВООБЩЕ. Пока вы обновляли страницу, до сервера не долетело
ничего. Сервер исправен и просто никого не слышит: режут выше него, в
сети хостера. Обратите внимание, что ssh на порт 22 при этом работает —
значит адрес живой, а глушат именно веб-порты. Это разговор с
поддержкой хостера, на сервере чинить нечего.
TXT
  exit 0
fi

echo
echo "-- Кто разговаривал (адреса, только входящие):"
grep ' In ' "$RAW" | srcip /dev/stdin 2>/dev/null | sort | uniq -c | sort -rn | head -10 \
  || awk '/ In /{print $5}' "$RAW" | sed 's/\.[0-9]*$//' | sort | uniq -c | sort -rn | head -10

echo
echo "-- Флаги:"
grep -o 'Flags \[[^]]*\]' "$RAW" | sort | uniq -c | sort -rn

echo
echo "-- Какой размер сегмента стороны объявили друг другу (опция mss в SYN):"
grep -E 'Flags \[S' "$RAW" | grep -o 'mss [0-9]*' | sort | uniq -c | sort -rn
echo "   Чем меньше mss, тем мельче пакеты. 1460 — обычная сеть."

echo
echo "-- Повторные отправки сервера (он говорит, ему не отвечают):"
awk '/ Out /{ if (match($0,/seq [0-9]+(:[0-9]+)?/)) { k=$7" "substr($0,RSTART,RLENGTH); c[k]++ } }
     END{ n=0; for (k in c) if (c[k]>1) { print "  " c[k] " раз: " k; n++ }
          if (n==0) print "  повторов нет" }' "$RAW" | head -15

echo
echo "-- Сколько соединений дошло до обмена данными:"
# Современные браузеры ставят в SYN пометки ECN, и флаг выглядит как
# [SEW] / [S.E], а не [S] / [S.]. Считаем по началу скобки.
echo "   запросов на соединение [S]:  $(grep -cE 'Flags \[S[EW]*\]' "$RAW")"
echo "   согласий сервера   [S.]:     $(grep -cE 'Flags \[S\.' "$RAW")"
echo "   передач данных     [P.]:     $(grep -cE 'Flags \[P' "$RAW")"
echo "   сбросов            [R]:      $(grep -cE 'Flags \[R' "$RAW")"

echo
echo "-- Каждое соединение по отдельности:"
awk '
function ep(s){ sub(/:$/,"",s); return s }
{
  if ($3=="In")       { c=ep($5) }
  else if ($3=="Out") { c=ep($7) }
  else next
  if (c=="") next
  seen[c]=1
  len=0
  if (match($0,/length [0-9]+$/)) len=substr($0,RSTART+7)+0
  if ($0 ~ /Flags \[S[EW]*\]/)  syn[c]++
  if ($0 ~ /Flags \[S\./)       sak[c]++
  if ($3=="In")  { inb[c]+=len;  inp[c]++ }
  else           { outb[c]+=len; outp[c]++ }
}
END{
  printf "   %-24s %4s %4s %9s %9s  %s\n", "посетитель", "зпр", "згл", "от него", "от нас", "чем кончилось"
  n=0
  for (c in seen) {
    if (inb[c]==0 && outb[c]==0) v="соединение без данных"
    else if (outb[c]==0)         v="СЕРВЕР НЕ ОТВЕТИЛ НИ БАЙТОМ"
    else if (inb[c]==0)          v="говорил только сервер"
    else                         v="обмен состоялся"
    printf "   %-24s %4d %4d %9d %9d  %s\n", c, syn[c], sak[c], inb[c], outb[c], v
    n++
    if (n>=25) { print "   ... (показаны первые 25)"; break }
  }
}' "$RAW"
cat <<'TXT'
   зпр — запросов на соединение, згл — согласий сервера, байты полезных данных.

   «СЕРВЕР НЕ ОТВЕТИЛ НИ БАЙТОМ» у всех соединений подряд — значит до
   сервера доходит только начало разговора. Если при этом у кого-то
   другого в том же отчёте «обмен состоялся», сервер точно исправен.
TXT

echo
echo "-- Не встают ли все соединения на одном и том же месте:"
awk '/ Out /{ if (match($0,/ack [0-9]+/)) { a=substr($0,RSTART+4,RLENGTH-4)+0; if (a>1) c[a]++ } }
     END{ n=0; for (k in c) { printf "   подтверждено %s байт — %d раз\n", k, c[k]; n++ }
          if (n==0) print "   данных от посетителя не было" }' "$RAW" | sort -k4 -n | head -10
cat <<'TXT'
   Если почти все соединения встают на ОДНОМ И ТОМ ЖЕ числе, близком
   к 1440, — это ровно один сетевой пакет. Значит от посетителя приходит
   первый пакет приветствия, а второй теряется по дороге. Сервер ждёт
   продолжения и молчит. Виноват не сервер и не размер страницы.
TXT

echo
cat <<'TXT'
Как читать:

  [S] есть, [S.] нет
      сервер не отвечает на запрос соединения — смотреть файрвол
      и очередь соединений на самом сервере.

  [S] и [S.] есть, но сервер повторяет [S.] по нескольку раз
      сервер согласился, а посетитель его согласия не получил.
      Ломается путь ОТ сервера К посетителю.

  Разговор дошёл до данных и встал, а сервер повторяет один и тот же
  кусок — ответ не доходит до посетителя, дело в размере пакета.

  Пришёл крупный кусок (около 1400 байт), сервер его подтвердил
  и замолчал — до него НЕ ДОШЛА вторая часть приветствия браузера.
  Ломается путь ОТ посетителя К серверу, и виноват размер пакета
  на входе, а не размер страницы.

  Разговор прошёл целиком, а сайт не открылся — дело не в сети.
TXT

echo
echo "-- Последние 60 строк как есть:"
tail -60 "$RAW"
} | tee "$OUT"

echo
echo "Разбор: $OUT"
echo "Все пакеты: $RAW"
