#!/usr/bin/env bash
# Доходят ли до сервера пакеты посетителя.
#
# Это последний вопрос, на который мы ещё не отвечали. Все прошлые замеры
# делались ИЗНУТРИ сервера и показывали, что он здоров. Но если пакеты до
# него просто не долетают, изнутри это выглядит ровно как тишина — сервер
# исправен и никого не видит.
#
# Скрипт слушает сетевую карту и записывает всё, что приходит на порты 80
# и 443. Пока он работает, надо с телефона пытаться открыть сайт.
#
#   Использование: sudo bash scripts/sniff.sh          # 60 секунд
#                  sudo bash scripts/sniff.sh 180      # 3 минуты
#
# Запускать В МОМЕНТ, КОГДА САЙТ НЕ ОТКРЫВАЕТСЯ.

set -u
SECS="${1:-60}"
OUT="$(dirname "$0")/../logs/sniff.txt"
mkdir -p "$(dirname "$OUT")"

if ! command -v tcpdump >/dev/null 2>&1; then
  echo "Ставлю tcpdump..."
  apt-get install -y tcpdump >/dev/null 2>&1 || {
    echo "Не удалось поставить tcpdump. Выполните: sudo apt install tcpdump"; exit 1; }
fi

RAW="$(mktemp)"
trap 'rm -f "$RAW"' EXIT

echo "==========================================================="
echo " Слушаю порты 80 и 443 в течение $SECS секунд."
echo
echo " СЕЙЧАС возьмите телефон и пробуйте открывать сайт:"
echo "   https://s-poryadok.ru/"
echo "   https://s-poryadok.ru/robots.txt"
echo " Обновляйте несколько раз, пока идёт отсчёт."
echo "==========================================================="
echo

timeout "$SECS" tcpdump -i any -nn -l -q 'tcp port 443 or tcp port 80' 2>/dev/null \
  | tee "$RAW" | tail -40

{
echo "Отчёт снят: $(date '+%F %T %Z')"
echo "Слушали $SECS секунд порты 80 и 443."
echo

TOTAL=$(wc -l < "$RAW")
echo "Всего пакетов поймано: $TOTAL"
echo

if [ "$TOTAL" -eq 0 ]; then
  cat <<'TXT'
ПАКЕТОВ НЕТ ВООБЩЕ.

Это ответ. Пока вы жали обновление на телефоне, до сервера не долетело
ни одного пакета. Сервер исправен и просто никого не слышит — его
запросы не доходят.

Причина находится ВЫШЕ сервера, в сети хостера: защита от атак,
фильтрация портов 80 и 443 или блокировка адреса. Обратите внимание,
что ssh на порт 22 при этом работает — значит адрес живой, а режут
именно веб-порты.

Что делать: писать в поддержку хостера, приложив этот отчёт и сказав
дословно: «сервер отвечает сам себе на 80 и 443, tcpdump не видит
входящих пакетов от клиентов, при этом ssh на 22 работает — прошу
проверить фильтрацию и защиту от атак на моём адресе 159.194.230.39».
Чинить на сервере при таком результате нечего.
TXT
else
  echo "-- Кто стучался (по адресам):"
  awk '{print $3}' "$RAW" | sed 's/\.[0-9]*$//' | sort | uniq -c | sort -rn | head -15
  echo
  echo "-- Что происходило (по флагам):"
  grep -o 'Flags \[[^]]*\]' "$RAW" | sort | uniq -c | sort -rn | head -10
  echo
  cat <<'TXT'
Как это читать:

  [S]      запрос на соединение от посетителя пришёл
  [S.]     сервер ответил согласием
  [.] [P.] пошли данные — соединение установилось
  [R] [R.] соединение сброшено
  [F.]     соединение закрыто нормально

Разбор:

  Есть [S], но нет [S.] — сервер не отвечает на запросы соединения.
      Смотреть очередь соединений и файрвол на самом сервере.

  Есть [S] и [S.], но дальше пусто — сервер ответил, а посетитель его
      ответа не получил. Ломается обратный путь: ответ до клиента
      не доходит. Это версия про размер пакета.

  Идут данные, потом [R] на середине — ответ рвётся при передаче.
      Тоже обратный путь и размер пакета.

  Всё проходит полностью, а сайт не открывается — значит браузер
      получил ответ, и дело не в сети.
TXT
fi
} | tee "$OUT"

echo
echo "Полный список пакетов и разбор — в $OUT"
cp "$RAW" "$(dirname "$OUT")/sniff-raw.txt" 2>/dev/null || true
